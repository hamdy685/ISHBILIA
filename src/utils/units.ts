const normalizeUnit = (unit?: string | null): string => {
  const trimmed = (unit || '').trim();
  if (!trimmed) return '';
  const aliasKey = UNIT_ALIASES[trimmed] || UNIT_ALIASES[trimmed.toUpperCase()];
  return (aliasKey || trimmed).toUpperCase();
};

export const getUnitLabel = (unit?: string | null): string => {
  const trimmed = (unit || '').trim();
  if (!trimmed) return '—';
  const normalized = normalizeUnit(trimmed);
  if (UNIT_LABELS[normalized]) return UNIT_LABELS[normalized];
  if (UNIT_ALIASES[trimmed] && UNIT_LABELS[UNIT_ALIASES[trimmed]]) return UNIT_LABELS[UNIT_ALIASES[trimmed]];
  if (UNIT_ALIASES[trimmed.toUpperCase()] && UNIT_LABELS[UNIT_ALIASES[trimmed.toUpperCase()]]) return UNIT_LABELS[UNIT_ALIASES[trimmed.toUpperCase()]];
  return trimmed;
};

export const getUnitValue = (unit?: string | null): string => {
  const normalized = normalizeUnit(unit);
  if (!normalized) return 'UNIT';
  if (UNIT_LABELS[normalized]) return normalized;
  const arabicEntry = Object.entries(UNIT_LABELS).find(([, label]) => label === unit?.trim());
  return arabicEntry?.[0] || normalized;
};

export const getUnitOptions = (units: string[]): Array<{ value: string; label: string }> =>
  units.map((value) => {
    if (value === 'BAR_3LINIA') return { value, label: 'سيخ 3 لينية (7.4 كجم)' };
    if (value === 'BAR_4LINIA') return { value, label: 'سيخ 4 لينية (10.4 كجم)' };
    if (value === 'BAR_5LINIA') return { value, label: 'سيخ 5 لينية (19 كجم)' };
    return { value, label: getUnitLabel(value) };
  });

